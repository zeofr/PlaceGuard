"""Eligibility checking routes — deterministic rule engine + gated registration."""

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel
from sqlalchemy.orm import Session

from api.routes.auth import get_current_student
from core.schemas import (
    Criterion,
    EligibilityResult,
    EligibilityStatus,
    Student as StudentSchema,
)
from database.connection import get_db
from database.crud import (
    create_registration,
    get_current_criteria,
    get_drive,
    get_registration,
    get_student,
)
from database.models import Student
from explanation.generator import generate_explanation_with_citations
from rules.eligibility_engine import evaluate_eligibility as check_eligibility

router = APIRouter(prefix="/eligibility", tags=["eligibility"])


class EligibilityCheckRequest(BaseModel):
    """Request to check student eligibility."""

    drive_id: str
    generate_explanation: bool = True


class CriterionResultResponse(BaseModel):
    """Criterion check result."""
    
    criterion_type: str
    operator: str
    value: str
    scope: str
    status: str
    student_value: str | None
    message: str


class EligibilityCheckResponse(BaseModel):
    """Eligibility check result with optional registration link."""
    
    student_id: str
    drive_id: str
    status: str
    explanation: str | None
    summary: str | None
    # Only populated when status == ELIGIBLE
    registration_link: str | None = None
    already_registered: bool = False
    criteria_results: list[CriterionResultResponse]
    criteria_checked: int
    criteria_passed: int
    criteria_failed: int
    criteria_unknown: int


@router.post("/check", response_model=EligibilityCheckResponse)
async def check_eligibility_endpoint(
    request: EligibilityCheckRequest,
    db: Session = Depends(get_db),
    student: Student = Depends(get_current_student),
):
    """Check if the logged-in student is eligible for a drive.

    - If ELIGIBLE: creates a Registration record (idempotent) and returns the
      registration link.
    - If INELIGIBLE / UNKNOWN: returns the reason without the link.
    - Explanation is generated by the LLM from the structured evidence.
    """
    # Get drive
    drive = get_drive(db, request.drive_id)
    if not drive:
        raise HTTPException(status_code=404, detail="Drive not found")

    # Get current criteria
    criteria_db = get_current_criteria(db, request.drive_id)
    if not criteria_db:
        raise HTTPException(
            status_code=404,
            detail="No criteria found for this drive. Ingest a notice first.",
        )

    # Build schema objects from the ORM student and criteria
    student_schema = StudentSchema(
        usn=student.usn,
        name=student.name,
        cgpa=student.cgpa,
        branch=student.branch,
        backlogs=student.backlogs,
        has_prior_offer=student.has_prior_offer,
        tenth_pct=student.tenth_pct,
        twelfth_pct=student.twelfth_pct,
    )

    import json as _json
    criteria = [
        Criterion(
            drive_id=c.drive_id,
            criterion_type=c.criterion_type,
            operator=c.operator,
            value=_json.loads(c.value),
            scope=c.scope,
        )
        for c in criteria_db
    ]

    # Run deterministic rule engine
    result = check_eligibility(student_schema, criteria)

    # Gate: only surface the link if ELIGIBLE
    registration_link = None
    already_registered = False

    if result.status == EligibilityStatus.ELIGIBLE:
        existing = get_registration(db, student.usn, request.drive_id)
        if existing:
            already_registered = True
        else:
            # Record the registration (idempotent via unique constraint)
            try:
                create_registration(
                    db,
                    usn=student.usn,
                    drive_id=request.drive_id,
                    eligibility_snapshot=result.model_dump(mode="json"),
                )
            except Exception:
                pass  # unique constraint hit — already registered
        registration_link = drive.registration_link

    # Generate explanation if requested
    explanation = None
    summary = None
    if request.generate_explanation:
        try:
            explanation_data = generate_explanation_with_citations(result)
            explanation = explanation_data["explanation"]
            summary = explanation_data["summary"]
        except Exception as e:
            explanation = f"(Explanation generation failed: {str(e)})"
            summary = "Eligibility determined, but explanation unavailable."

    criteria_results_response = [
        CriterionResultResponse(
            criterion_type=cr.criterion.criterion_type,
            operator=cr.criterion.operator,
            value=str(cr.criterion.value),
            scope=cr.criterion.scope,
            status=cr.status.value,
            student_value=str(cr.student_value) if cr.student_value is not None else None,
            message=cr.message,
        )
        for cr in result.criterion_results
    ]

    return EligibilityCheckResponse(
        student_id=result.student_id,
        drive_id=result.drive_id,
        status=result.status.value,
        explanation=explanation,
        summary=summary,
        registration_link=registration_link,
        already_registered=already_registered,
        criteria_results=criteria_results_response,
        criteria_checked=len(result.criterion_results),
        criteria_passed=sum(1 for cr in result.criterion_results if cr.status.value == "PASS"),
        criteria_failed=sum(1 for cr in result.criterion_results if cr.status.value == "FAIL"),
        criteria_unknown=sum(1 for cr in result.criterion_results if cr.status.value == "UNKNOWN"),
    )
